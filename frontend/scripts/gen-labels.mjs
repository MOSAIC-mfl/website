// Writes src/lib/domain/vocab-labels.ts: the display labels of the coded values the website shows
// (filters and dataset pages), taken from the MOSAIC standard's vocabularies. The API has no
// filters endpoint (mosaic-api ADR-0007): the website keeps these lists, and this script refreshes
// them when the standard changes.
//
//   node scripts/gen-labels.mjs ../../mosaic-standard/vocab     (or a catalogue build's dist/vocab)
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const dir = process.argv[2]
if (!dir) {
  console.error('usage: node scripts/gen-labels.mjs <path to the standard vocab/ folder>')
  process.exit(2)
}
// facet of the website -> vocabulary file of the standard (as mosaic-api FACET_VOCAB)
const FACET_VOCAB = {
  theme: 'themes',
  landscape: 'landscapes',
  geography: 'geography',
  resource_type: 'resource_type',
  data_kind: 'data_kind',
  method: 'access_method',
  access: 'access',
}
const labels = {}
let version = ''
for (const [facet, file] of Object.entries(FACET_VOCAB)) {
  const v = JSON.parse(readFileSync(resolve(dir, `${file}.json`), 'utf8'))
  version ||= v.scheme?.version ?? ''
  labels[facet] = Object.fromEntries(v.concepts.map((c) => [c.id, c.label]))
}
const body = `/* Generated by scripts/gen-labels.mjs from the MOSAIC standard's vocabularies${version ? ` (v${version})` : ''}. Do not edit. */
/** Display label of each coded value, per facet (theme, landscape, geography, ...). */
export const VOCAB_LABELS: Record<string, Record<string, string>> = ${JSON.stringify(labels, null, 2)}
`
writeFileSync(resolve(here, '../src/lib/domain/vocab-labels.ts'), body)
console.log(`src/lib/domain/vocab-labels.ts written (${Object.values(labels).reduce((n, l) => n + Object.keys(l).length, 0)} labels)`)
